package sqala.codegen

import scala.collection.mutable

final case class GeneratedEntity(
    className: String,
    fileName: String,
    content: String
)

object EntityGenerator {
    def generate(
        table: TableSchema,
        config: CodegenConfig,
        warn: String => Unit
    ): Option[GeneratedEntity] = {
        val className = Naming.tableClassName(table.name, config.tableNaming)
        val usedFields = mutable.Set.empty[String]
        val mapped = mutable.ArrayBuffer.empty[MappedColumn]

        table.columns.foreach { column =>
            if (column.generated) {
                warn("Skipping generated column " + table.name + "." + column.name)
            } else {
                TypeMapper.map(column, config.typeMappings) match {
                    case Right(mappedType) =>
                        mappedType.warning.foreach { warning =>
                            warn("Column " + table.name + "." + column.name + ": " + warning)
                        }
                        val baseField = Naming.fieldName(column.name)
                        val field = uniqueField(baseField, usedFields)
                        usedFields += field
                        mapped += MappedColumn(
                            column = column,
                            field = field,
                            scalaType = mappedType.scalaType,
                            primaryKey = table.primaryKeys.contains(column.name)
                        )
                    case Left(error) =>
                        warn(
                            "Skipping column " + table.name + "." + column.name + ": " + error
                        )
                }
            }
        }

        if (mapped.isEmpty) {
            warn("Skipping table " + table.name + ": no supported columns")
            None
        } else {
            val mappedNames = mapped.map(_.column.name).toSet
            val missingPrimaryKeys = table.primaryKeys.diff(mappedNames)
            if (missingPrimaryKeys.nonEmpty) {
                warn(
                    "Skipping table " + table.name + ": unsupported primary key columns " +
                        missingPrimaryKeys.toSeq.sorted.mkString(", ")
                )
                None
            } else {
                val content = render(className, table, mapped.toSeq, config.outputPackage)
                Some(GeneratedEntity(className, className + ".scala", content))
            }
        }
    }

    private def uniqueField(base: String, used: mutable.Set[String]): String = {
        if (!used.contains(base)) {
            base
        } else {
            var index = 2
            while (used.contains(base + "_" + index)) {
                index += 1
            }
            base + "_" + index
        }
    }

    private def render(
        className: String,
        table: TableSchema,
        columns: Seq[MappedColumn],
        outputPackage: String
    ): String = {
        val needsColumn = columns.exists(_.needsColumnAnnotation)
        val needsPrimaryKey = columns.exists(_.primaryKey)
        val needsAutoInc = columns.exists(c => c.primaryKey && c.column.autoIncrement)

        val imports = mutable.ArrayBuffer.empty[String]
        imports += "import sqala.metadata.table"
        if (needsColumn) imports += "import sqala.metadata.column"
        if (needsPrimaryKey) imports += "import sqala.metadata.primaryKey"
        if (needsAutoInc) imports += "import sqala.metadata.autoInc"

        val builder = new StringBuilder
        builder.append("// Generated by sqala-codegen. Do not edit.\n")
        if (outputPackage.nonEmpty) {
            builder.append("package ").append(outputPackage).append("\n\n")
        }
        imports.foreach(line => builder.append(line).append("\n"))
        builder.append("\n")
        builder.append("@table(").append(quote(table.name)).append(")\n")
        builder.append("case class ").append(className).append("(\n")
        columns.zipWithIndex.foreach { case (column, index) =>
            val annotations = mutable.ArrayBuffer.empty[String]
            if (column.primaryKey) {
                annotations += "@primaryKey"
            }
            if (column.primaryKey && column.column.autoIncrement) {
                annotations += "@autoInc"
            }
            if (column.needsColumnAnnotation) {
                annotations += "@column(" + quote(column.column.name) + ")"
            }
            builder.append("    ")
            annotations.foreach(a => builder.append(a).append(" "))
            builder.append(Naming.escapeField(column.field)).append(": ")
            if (column.column.nullable && !column.primaryKey) {
                builder.append("Option[").append(column.scalaType).append("]")
            } else {
                builder.append(column.scalaType)
            }
            if (index != columns.size - 1) {
                builder.append(",")
            }
            builder.append("\n")
        }
        builder.append(")\n")
        builder.toString
    }

    private def quote(value: String): String = {
        "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"") + "\""
    }

    private final case class MappedColumn(
        column: ColumnSchema,
        field: String,
        scalaType: String,
        primaryKey: Boolean
    ) {
        def needsColumnAnnotation: Boolean = {
            Naming.snakeCase(field) != column.name
        }
    }
}
